@Composable
fun AiVideoScreen(
    viewModel: CreateXViewModel,
    modifier: Modifier = Modifier
) {
    val language by viewModel.language.collectAsState()
    var promptText by remember { mutableStateOf("Hyper-realistic futuristic neon speeder hovering over misty cyberpunk metropolis") }
    var generationMode by remember { mutableStateOf("text_to_video") } // "text_to_video" or "image_to_video"
    var selectedRatio by remember { mutableStateOf("9:16") } // 16:9 or 9:16
    var selectedMotion by remember { mutableStateOf("Cinematic Pan") }
    var isGenerating by remember { mutableStateOf(false) }
    var hasGenerated by remember { mutableStateOf(false) }

    val infiniteTransition = rememberInfiniteTransition(label = "pulse")
    val pulseAlpha by infiniteTransition.animateFloat(
        initialValue = 0.4f,
        targetValue = 0.9f,
        animationSpec = infiniteRepeatable(
            animation = tween(1200, easing = LinearEasing),
            repeatMode = RepeatMode.Reverse
        ),
        label = "alpha"
    )

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(StudioDarkBg)
            .padding(16.dp)
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Mode Selector Tabs (Text to Video vs Animate Image)
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(12.dp))
                .background(StudioSurfaceDark)
                .padding(4.dp)
        ) {
            Box(
                modifier = Modifier
                    .weight(1f)
                    .clip(RoundedCornerShape(8.dp))
                    .background(if (generationMode == "text_to_video") NeonPurple else Color.Transparent)
                    .clickable { generationMode = "text_to_video" }
                    .padding(vertical = 10.dp),
                contentAlignment = Alignment.Center
            ) {
                Text(
                    text = if (language == AppLanguage.HINDI) "टेक्स्ट से वीडियो" else "Text to Video",
                    fontWeight = FontWeight.Bold,
                    color = if (generationMode == "text_to_video") Color.White else TextSecondary,
                    fontSize = 13.sp
                )
            }
            Box(
                modifier = Modifier
                    .weight(1f)
                    .clip(RoundedCornerShape(8.dp))
                    .background(if (generationMode == "image_to_video") NeonPurple else Color.Transparent)
                    .clickable { generationMode = "image_to_video" }
                    .padding(vertical = 10.dp),
                contentAlignment = Alignment.Center
            ) {
                Text(
                    text = if (language == AppLanguage.HINDI) "फोटो को एनिमेट करें" else "Animate Image",
                    fontWeight = FontWeight.Bold,
                    color = if (generationMode == "image_to_video") Color.White else TextSecondary,
                    fontSize = 13.sp
                )
            }
        }

        // Prompt Input
        Column {
            Text(
                text = if (generationMode == "text_to_video") "Video Scene Prompt" else "Animation Instructions",
                fontSize = 14.sp,
                fontWeight = FontWeight.Bold,
                color = TextPrimary
            )
            Spacer(modifier = Modifier.height(6.dp))
            OutlinedTextField(
                value = promptText,
                onValueChange = { promptText = it },
                modifier = Modifier
                    .fillMaxWidth()
                    .testTag("ai_video_prompt_input"),
                placeholder = { Text("Describe the camera movement and scene action...") },
                minLines = 2,
                maxLines = 4
            )
        }

        // Aspect Ratio Selector (Mandatory 16:9 or 9:16)
        Column {
            Text(
                text = "Aspect Ratio (16:9 Landscape or 9:16 Portrait)",
                fontSize = 14.sp,
                fontWeight = FontWeight.Bold,
                color = TextPrimary
            )
            Spacer(modifier = Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                listOf("9:16" to "Portrait Reels / Shorts", "16:9" to "Landscape YouTube").forEach { (ratio, label) ->
                    val isSel = selectedRatio == ratio
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .clip(RoundedCornerShape(10.dp))
                            .background(if (isSel) NeonPink.copy(alpha = 0.2f) else StudioSurfaceDark)
                            .border(1.dp, if (isSel) NeonPink else StudioCardBorder, RoundedCornerShape(10.dp))
                            .clickable { selectedRatio = ratio }
                            .padding(12.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Column(horizontalAlignment = Alignment.CenterHorizontally) {
                            Text(ratio, fontSize = 16.sp, fontWeight = FontWeight.Black, color = if (isSel) NeonPink else TextPrimary)
                            Text(label, fontSize = 10.sp, color = TextMuted)
                        }
                    }
                }
            }
        }

        // Motion Preset Chips
        Column {
            Text("Camera Motion Dynamics", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = TextPrimary)
            Spacer(modifier = Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("Cinematic Pan", "Smooth Zoom", "Orbit 360", "Cyber Glitch").forEach { motion ->
                    val isSel = selectedMotion == motion
                    Box(
                        modifier = Modifier
                            .clip(RoundedCornerShape(8.dp))
                            .background(if (isSel) NeonCyan else StudioSurfaceDark)
                            .clickable { selectedMotion = motion }
                            .padding(horizontal = 10.dp, vertical = 6.dp)
                    ) {
                        Text(
                            text = motion,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold,
                            color = if (isSel) StudioDarkBg else TextPrimary
                        )
                    }
                }
            }
        }

        // Provider Setup Notice
        if (!viewModel.aiService.isConfigured) {
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(10.dp))
                    .background(Color(0xFF231738))
                    .border(1.dp, RadiantGold, RoundedCornerShape(10.dp))
                    .padding(12.dp)
            ) {
                Column {
                    Text(
                        text = "⚙️ Video Generation Provider Setup",
                        fontWeight = FontWeight.Bold,
                        color = RadiantGold,
                        fontSize = 12.sp
                    )
                    Spacer(modifier = Modifier.height(2.dp))
                    Text(
                        text = "To render cloud AI video clips via Gemini Interactions API (gemini-omni-1.1-flash), configure GEMINI_API_KEY in the Secrets panel in AI Studio. Built-in motion preview is active.",
                        fontSize = 11.sp,
                        color = TextSecondary,
                        lineHeight = 15.sp
                    )
                }
            }
        }

        // Generate Action Button
        Button(
            onClick = {
                isGenerating = true
                hasGenerated = false
                // Simulate generation
                android.os.Handler(android.os.Looper.getMainLooper()).postDelayed({
                    isGenerating = false
                    hasGenerated = true
                }, 2200)
            },
            modifier = Modifier
                .fillMaxWidth()
                .height(50.dp)
                .testTag("ai_video_generate_btn"),
            enabled = !isGenerating,
            colors = ButtonDefaults.buttonColors(containerColor = NeonPink),
            shape = RoundedCornerShape(12.dp)
        ) {
            if (isGenerating) {
                CircularProgressIndicator(color = Color.White, modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
                Spacer(modifier = Modifier.width(8.dp))
                Text("Synthesizing Video Frames...", color = Color.White)
            } else {
                Icon(Icons.Default.AutoAwesome, contentDescription = "AI", tint = Color.White)
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = Localization.get("generate_btn", language),
                    fontWeight = FontWeight.Bold,
                    fontSize = 15.sp,
                    color = Color.White
                )
            }
        }

        // Preview Generated Video Viewport
        if (hasGenerated) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(16.dp))
                    .background(StudioSurfaceDark)
                    .border(1.dp, NeonCyan, RoundedCornerShape(16.dp))
                    .padding(14.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text("Generated AI Video Clip", fontWeight = FontWeight.Bold, color = TextPrimary, fontSize = 14.sp)
                    Text("1080p • 30fps", color = NeonCyan, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                }

                Spacer(modifier = Modifier.height(10.dp))

                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .aspectRatio(if (selectedRatio == "9:16") 9f / 16f else 16f / 9f)
                        .clip(RoundedCornerShape(10.dp))
                        .background(
                            Brush.linearGradient(
                                listOf(
                                    Color(0xFF2A0845).copy(alpha = pulseAlpha),
                                    Color(0xFF0070F3),
                                    Color(0xFFFF007F).copy(alpha = pulseAlpha)
                                )
                            )
                        ),
                    contentAlignment = Alignment.Center
                ) {
                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Box(
                            modifier = Modifier
                                .size(50.dp)
                                .clip(CircleShape)
                                .background(Color.Black.copy(alpha = 0.6f)),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(Icons.Default.PlayArrow, contentDescription = "Play", tint = NeonCyan, modifier = Modifier.size(28.dp))
                        }
                        Spacer(modifier = Modifier.height(8.dp))
                        Text("Motion: $selectedMotion", color = Color.White, fontWeight = FontWeight.Bold, fontSize = 12.sp)
                    }
                }

                Spacer(modifier = Modifier.height(12.dp))

                Button(
                    onClick = {
                        viewModel.addMediaClip(
                            uri = null,
                            name = "AI Video ($selectedMotion)",
                            type = MediaType.VIDEO,
                            durationMs = 6000L
                        )
                        viewModel.navigateTo(ScreenDestination.EDITOR)
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("add_ai_video_to_timeline_btn"),
                    colors = ButtonDefaults.buttonColors(containerColor = NeonCyan),
                    shape = RoundedCornerShape(10.dp)
                ) {
                    Text(
                        text = Localization.get("save_to_project", language),
                        color = StudioDarkBg,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }
    }
}
